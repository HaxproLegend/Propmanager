def test_postgres_translation_helpers_are_portable():
    assert auth_app.pg_sql("SELECT * FROM users WHERE email=? AND role=?") == "SELECT * FROM users WHERE email=%s AND role=%s"
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in auth_app.pg_ddl(
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT); PRAGMA foreign_keys = ON;")
    assert auth_app.pg_sql("SELECT '%' AS literal, ? AS value") == "SELECT '%%' AS literal, %s AS value"
    assert "strftime" in auth_app.month_expression("a.created_at")


def test_api_sends_hardening_headers(client):
    response = client.get("/api/health")
    assert response.headers["X-Content-Type-Options"] == "nosniff"
    assert response.headers["X-Frame-Options"] == "DENY"
    assert response.headers["Referrer-Policy"] == "strict-origin-when-cross-origin"
    assert "default-src 'none'" in response.headers["Content-Security-Policy"]


def test_org_settings_drive_advisory_overdue_flags(client):
    owner = client
    renter = auth_app.app.test_client()
    register(owner, "owner@example.test", "owner", "Portfolio Owner")
    register(renter, "renter@example.test")
    org_id = post_json(owner, "/api/orgs", {"name": "Northstar", "slug": "northstar"}).get_json()["organization"]["id"]
    assert patch_json(owner, f"/api/orgs/{org_id}/settings", {"overdue_hours": 1, "escalation_hours": 2}).status_code == 200

    property_id = post_json(owner, "/api/properties", {
        "title": "Garden Flats", "address": "12 Park Road, Pune", "monthly_rent": 28000,
    }).get_json()["property"]["id"]
    post_json(owner, f"/api/orgs/{org_id}/properties/{property_id}", {})
    application_id = post_json(renter, "/api/applications", {"property_id": property_id}).get_json()["id"]
    post_json(owner, f"/api/applications/{application_id}/decision", {"status": "Accepted"})
    ticket_id = post_json(renter, "/api/tickets", {
        "property_id": property_id, "title": "Leaking tap", "description": "The tap keeps dripping",
    }).get_json()["id"]
    with auth_app.connect() as db:
        db.execute("UPDATE maintenance_tickets SET created_at=?,updated_at=? WHERE id=?",
                   (int(time.time()) - 10 * 3600, int(time.time()) - 10 * 3600, ticket_id))

    row = next(row for row in owner.get("/api/tickets").get_json()["tickets"] if row["id"] == ticket_id)
    assert row["is_overdue"] is True
    assert row["is_escalated"] is True
    assert row["sla_due_at"] < row["created_at"] + 2 * 3600


def test_vendor_assignment_operations_photos_and_audit(client):
    owner = client
    renter = auth_app.app.test_client()
    broker = auth_app.app.test_client()
    register(owner, "owner@example.test", "owner", "Portfolio Owner")
    register(renter, "renter@example.test")
    create_broker()
    login(broker, "broker@example.test")
    org_id = post_json(owner, "/api/orgs", {"name": "Northstar", "slug": "northstar"}).get_json()["organization"]["id"]

    property_id = post_json(owner, "/api/properties", {
        "title": "Garden Flats", "address": "12 Park Road, Pune", "monthly_rent": 28000,
    }).get_json()["property"]["id"]
    post_json(owner, f"/api/orgs/{org_id}/properties/{property_id}", {})
    application_id = post_json(renter, "/api/applications", {"property_id": property_id}).get_json()["id"]
    post_json(owner, f"/api/applications/{application_id}/decision", {"status": "Accepted"})
    ticket_id = post_json(renter, "/api/tickets", {
        "property_id": property_id, "title": "Leaking tap", "description": "The tap keeps dripping",
    }).get_json()["id"]

    vendor = post_json(broker, f"/api/orgs/{org_id}/vendors", {
        "name": "Rapid Plumbers", "service_type": "Plumbing", "phone": "99999",
    })
    assert vendor.status_code == 201
    vendor_id = vendor.get_json()["vendor"]["id"]
    owner_id = owner.get("/api/auth/me").get_json()["user"]["id"]
    scheduled = int(time.time()) + 86400
    operation = patch_json(broker, f"/api/tickets/{ticket_id}/operations", {
        "assignee_id": owner_id, "vendor_id": vendor_id, "scheduled_at": scheduled,
        "repair_cost_paise": 125000, "emergency": True,
    })
    assert operation.status_code == 200
    assert operation.get_json()["ticket"]["repair_cost_paise"] == 125000
    assert operation.get_json()["ticket"]["emergency"] == 1

    photo = post_json(renter, f"/api/tickets/{ticket_id}/photos", {
        "url": "https://images.example.test/leak.jpg", "caption": "Leaking pipe",
    })
    assert photo.status_code == 201
    assert post_json(renter, f"/api/tickets/{ticket_id}/photos", {"url": "javascript:alert(1)"}).status_code == 400

    detail = owner.get(f"/api/tickets/{ticket_id}").get_json()
    assert detail["photos"][0]["caption"] == "Leaking pipe"
    assert detail["ticket"]["assignee_name"] == "Portfolio Owner"
    assert detail["ticket"]["vendor_name"] == "Rapid Plumbers"
    assert any(event["event_type"] == "operation" for event in detail["history"])

    audit = owner.get(f"/api/orgs/{org_id}/audit").get_json()["events"]
    assert {event["action"] for event in audit} >= {"vendor.created", "ticket.operations", "ticket.photo_added", "application.accepted"}


def test_org_members_see_linked_properties_and_backup_retention(client, tmp_path):
    owner = client
    other_owner = auth_app.app.test_client()
    register(owner, "owner@example.test", "owner", "Portfolio Owner")
    register(other_owner, "other@example.test", "owner", "Other Owner")
    org_id = post_json(owner, "/api/orgs", {"name": "Northstar", "slug": "northstar"}).get_json()["organization"]["id"]
    foreign = post_json(other_owner, "/api/properties", {
        "title": "Shared Office", "address": "9 Lake Road, Pune", "monthly_rent": 90000,
    }).get_json()["property"]["id"]
    with auth_app.connect() as db:
        db.execute("UPDATE properties SET org_id=? WHERE id=?", (org_id, foreign))
    titles = [row["title"] for row in owner.get("/api/properties").get_json()["properties"]]
    third_owner = auth_app.app.test_client()
    register(third_owner, "third@example.test", "owner", "Third Owner")
    post_json(third_owner, "/api/properties", {
        "title": "Private Flat", "address": "3 Hill Road, Pune", "monthly_rent": 24000,
    })
    assert "Shared Office" in titles
    assert "Private Flat" not in titles
    assert "Shared Office" in [row["title"] for row in other_owner.get("/api/properties").get_json()["properties"]]

    backup_path = tmp_path / "fresh.backup.sqlite3"
    old_path = tmp_path / "old.backup.sqlite3"
    old_path.write_text("old backup")
    old_time = time.time() - 10 * 86400
    os.utime(old_path, (old_time, old_time))
    result = auth_app.app.test_cli_runner().invoke(args=["backup", "--output", str(backup_path), "--retention-days", "7"])
    assert result.exit_code == 0, result.output
    assert backup_path.exists()
    assert not old_path.exists()
    assert "Removed 1 backups" in result.output
